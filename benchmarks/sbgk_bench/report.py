    # ---------------------------------------------------------------- caveats
    A("## 10. Methodological caveats")
    A("")
    caveats = [
        "**EXP-3 does not measure an LLM.** The agent is scripted; \"repair success\" means that applying the kernel's feedback mechanically leads to the reference root. "
        "For an ambiguous alias and an unsupported premise the scripted agent knows which candidate it \"meant\". The real repair rate of an LLM needs a live experiment.",
        "**Bytes instead of tokens and prices.** Tokens are estimated as bytes/4; kernel answers and agent output are added with equal weight. The gain of the streaming scheme over the JSON patch (about "
        f"{f0(ar['A2']['B_saves_total_pct'])} %) is comparable to the error of such an estimate; over full regeneration it is robust.",
        "**Synthetic corpora.** The policies are generated from templated sentences; on real documents (tables, repeated wording, non-ASCII) chunk preservation and the share of quotes on boundaries will differ. "
        "The throughput of the chunkers was not measured.",
        "**FastCDC vs LocalMax.** The result \"FastCDC < 90 %\" holds for these parameters (min 512 / avg 1024 / max 2048) and documents of 20–50 KB (≈ 26–32 chunks); "
        "with a smaller average chunk size the share of preserved chunks would probably grow (not tested). LocalMax gives a lower bound on chunk length of ≈ 513 B and allows forced cuts at `max`.",
        "**Conflicts.** When a `POS/NEG` pair exists the kernel recomputes the statuses of the whole graph (O(N) per operation); incrementality holds only without conflicts. The conflict mode was measured only on small graphs and in tests.",
        "**The rule language is narrow.** Rules are Horn rules with equalities between premise fields and constants in the head; no negation, no arithmetic, no proof search: the kernel checks derivations proposed by the agent but does not find them itself. "
        "The ontology (entities, aliases, predicates) is given in advance; building it is a separate task.",
        "**Tamper evidence is detection, not prevention.** Whoever can rewrite all sections of the container consistently gets an internally valid file. "
        "An external anchoring of `state_merkle_root` / the chain head (signature, registry) is needed. The hash is unkeyed SHA-256.",
        "**Time travel is O(prefix).** There are no checkpoints and no `mmap`; the container is rebuilt in memory on append (sections are rebuilt), the WAL inside it is append-only. Scale was checked up to ~86 k nodes.",
        "**Memory** was measured by an allocator counter inside the process (allocation peak during an operation), not RSS; the EXP-4 table gives both.",
        "**One machine, one thread, no warm-up and no repeats across processes.** Times are medians/percentiles inside the process, excluding the start of `sbgk` and file reads; "
        "microsecond values drift 1.5–2× from run to run (OS noise), so orders of magnitude are what should be compared.",
        "**A quote is an exact byte match.** Differences in whitespace / Unicode normalization give `QUOTE_NOT_FOUND_IN_BYTES` by design; the offered candidates are a hint, not an acceptance.",
        "**Development finding (EXP-6; numbers from the run log).** The first version of the format missed some chain-recomputing tamperings: 8 of 60 in the first run and 1 of 400 after the first fix; after tightening the format — 400 of 400 caught. "
        "This shows that \"every bit affects the state\" has to be checked separately, and that an exhaustive bit sweep of a small container and a chain-recomputing attack are mandatory tests.",
    ]
